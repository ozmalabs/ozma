//! Run a loopback, view-only FreeRDP shadow output or inspect the OZFR stream.
//!
//! Three output paths are available:
//! - BMP files or raw RGBA for offline inspection.
//! - The original Xvfb + ffplay + `freerdp-shadow-cli3` prototype.
//! - A direct-surface FreeRDP bridge (see `rdp-direct/rdp-direct.c`) that reads
//!   OZFR unchanged and publishes frames straight into the shadow server's
//!   primary surface. The Rust side only forwards stdin to that helper.

use std::{
    fs::{self, File},
    io::{self, BufWriter, Write},
    path::{Path, PathBuf},
    process::{Command, Stdio},
};

use anyhow::{Context, Result};
use clap::Parser;
use ozma_client::rdp::{RdpFrameLayout, RdpFrameReader};

#[derive(Debug, Parser)]
struct Args {
    /// Directory receiving numbered 32-bit BMP desktop frames.
    #[arg(long, default_value = ".")]
    output_dir: PathBuf,
    /// Stop after this many frames (zero means until EOF).
    #[arg(long, default_value_t = 0)]
    max_frames: u64,
    /// Write packed RGBA8 frames to stdout for ffplay/Xvfb or another desktop
    /// capture bridge instead of creating BMP files.
    #[arg(long)]
    raw_rgba: bool,
    /// Serve RDP through FreeRDP shadow on an isolated virtual X11 display.
    #[arg(long, conflicts_with = "raw_rgba")]
    shadow_port: Option<u16>,
    /// Run the compiled direct-surface bridge at PATH (for example
    /// `ozma-client/examples/rdp-direct/rdp-direct`) and forward the OZFR
    /// stream to it unchanged.
    #[arg(long, value_name = "PATH", conflicts_with_all = ["raw_rgba", "shadow_port"])]
    direct_surface: Option<PathBuf>,
    /// RDP port used by `--direct-surface`.
    #[arg(long, default_value_t = 3390)]
    port: u16,
    /// Bind address used by `--direct-surface` (loopback by default).
    #[arg(long, default_value = "127.0.0.1")]
    bind: String,
    /// Credential file consumed by `--direct-surface` (`user:secret` or a bare
    /// token). Without this, the bridge generates a token file.
    #[arg(long)]
    auth_file: Option<PathBuf>,
    /// Token file generated by `--direct-surface` when no credential file is
    /// supplied.
    #[arg(long)]
    token_file: Option<PathBuf>,
    /// Username paired with a generated token.
    #[arg(long)]
    user: Option<String>,
    /// Maximum concurrent authorized viewers for `--direct-surface`.
    #[arg(long, default_value_t = 1)]
    max_viewers: u32,
    /// FreeRDP certificate/config directory used by `--direct-surface`.
    #[arg(long)]
    config_dir: Option<PathBuf>,
}

fn main() -> Result<()> {
    let args = Args::parse();
    if let Some(bridge) = &args.direct_surface {
        return direct_surface(bridge, &args);
    }
    let stdin = io::stdin();
    let mut reader = RdpFrameReader::new(stdin.lock());
    if let Some(port) = args.shadow_port {
        return shadow(reader, port);
    }
    if !args.raw_rgba {
        fs::create_dir_all(&args.output_dir).context("creating RDP bridge output directory")?;
    }
    let mut count = 0_u64;
    while let Some((index, layout, rgba)) = reader.next_frame().context("reading OZFR frame")? {
        if args.raw_rgba {
            let row_bytes = layout.width as usize * 4;
            let mut stdout = io::stdout().lock();
            for row in rgba.chunks_exact(layout.stride as usize) {
                stdout.write_all(&row[..row_bytes])?;
            }
        } else {
            let path = args.output_dir.join(format!("frame-{index:08}.bmp"));
            write_bmp(&path, layout, &rgba)
                .with_context(|| format!("writing {}", path.display()))?;
        }
        count += 1;
        if args.max_frames != 0 && count >= args.max_frames {
            break;
        }
    }
    eprintln!(
        "RDP frame bridge wrote {count} frame(s) ({})",
        if args.raw_rgba { "raw RGBA" } else { "BMP" }
    );
    Ok(())
}

fn direct_surface(bridge: &Path, args: &Args) -> Result<()> {
    anyhow::ensure!(
        bridge.is_file(),
        "direct-surface bridge {} not found; compile it with: cc -O2 -Wall \
         ozma-client/examples/rdp-direct/rdp-direct.c \
         $(pkg-config --cflags --libs freerdp-shadow3) -o <path>",
        bridge.display()
    );

    let mut command = Command::new(bridge);
    command
        .arg("--port")
        .arg(args.port.to_string())
        .arg("--bind")
        .arg(&args.bind)
        .arg("--max-viewers")
        .arg(args.max_viewers.to_string())
        .stdin(Stdio::piped())
        .stdout(Stdio::inherit())
        .stderr(Stdio::inherit());
    if let Some(path) = &args.auth_file {
        command.arg("--auth-file").arg(path);
    }
    if let Some(path) = &args.token_file {
        command.arg("--token-file").arg(path);
    }
    if let Some(user) = &args.user {
        command.arg("--user").arg(user);
    }
    if let Some(path) = &args.config_dir {
        command.arg("--config-dir").arg(path);
    }

    let mut child = command
        .spawn()
        .with_context(|| format!("spawning direct-surface bridge {}", bridge.display()))?;
    let mut child_stdin = child.stdin.take().context("opening bridge stdin")?;
    let copy_result = io::copy(&mut io::stdin().lock(), &mut child_stdin);
    drop(child_stdin);
    let status = child.wait().context("waiting for direct-surface bridge")?;
    copy_result.context("forwarding OZFR stream to the direct-surface bridge")?;
    anyhow::ensure!(
        status.success(),
        "direct-surface RDP bridge exited with {status}"
    );
    Ok(())
}

fn shadow(mut frames: RdpFrameReader<impl io::Read>, port: u16) -> Result<()> {
    let Some((_, layout, first)) = frames.next_frame()? else {
        anyhow::bail!("no initial RGBA frame");
    };
    anyhow::ensure!(port != 0, "choose a nonzero shadow port");
    let size = format!("{}x{}", layout.width, layout.height);
    let screen = format!("-screen 0 {size}x24 -nolisten tcp");
    let size_arg = format!("/rect:0,0,{},{}", layout.width, layout.height);
    let port_arg = format!("/port:{port}");
    let shell = r#"
set -eu
exec 3<&0
SDL_VIDEODRIVER=x11 ffplay -autoexit -loglevel error -fs -noborder -probesize 32 -analyzeduration 0 \
  -f rawvideo -pixel_format rgba -video_size "$1" -framerate 30 -i pipe:0 <&3 3<&- &
exec 3<&-
player=$!
shadow=
cleanup() {
  kill "$player" 2>/dev/null || :
  if [ -n "$shadow" ]; then kill "$shadow" 2>/dev/null || :; fi
  wait || :
}
trap cleanup EXIT
trap 'exit 1' HUP INT TERM
freerdp-shadow-cli3 /bind-address:127.0.0.1 "$2" "$3" -auth -may-interact /sec:tls &
shadow=$!
wait "$player"
"#;
    let mut child = Command::new("xvfb-run")
        .args([
            "-a", "-s", &screen, "sh", "-c", shell, "ozma-rdp", &size, &port_arg, &size_arg,
        ])
        .stdin(Stdio::piped())
        .spawn()
        .context("launching Xvfb, ffplay and FreeRDP shadow")?;
    let mut pipe = child.stdin.take().context("opening RDP display pipe")?;
    let result = (|| -> Result<()> {
        write_rgba(&mut pipe, layout, &first)?;
        while let Some((_, layout, rgba)) = frames.next_frame()? {
            if child.try_wait()?.is_some() {
                anyhow::bail!("RDP display backend exited");
            }
            write_rgba(&mut pipe, layout, &rgba)?;
        }
        Ok(())
    })();
    drop(pipe);
    let status = child.wait()?;
    result?;
    anyhow::ensure!(status.success(), "RDP display backend exited with {status}");
    Ok(())
}

fn write_rgba(out: &mut impl Write, layout: RdpFrameLayout, rgba: &[u8]) -> io::Result<()> {
    let row_bytes = layout.width as usize * 4;
    for row in rgba.chunks_exact(layout.stride as usize) {
        out.write_all(&row[..row_bytes])?;
    }
    Ok(())
}

fn write_bmp(path: &PathBuf, layout: RdpFrameLayout, rgba: &[u8]) -> Result<()> {
    let row_bytes = layout.width as usize * 4;
    let image_bytes = row_bytes * layout.height as usize;
    let file_size = 54 + image_bytes;
    let mut out = BufWriter::new(File::create(path)?);
    out.write_all(b"BM")?;
    out.write_all(&(file_size as u32).to_le_bytes())?;
    out.write_all(&[0; 4])?;
    out.write_all(&(54_u32).to_le_bytes())?;
    out.write_all(&(40_u32).to_le_bytes())?;
    out.write_all(&(layout.width as i32).to_le_bytes())?;
    out.write_all(&(layout.height as i32).to_le_bytes())?;
    out.write_all(&(1_u16).to_le_bytes())?;
    out.write_all(&(32_u16).to_le_bytes())?;
    out.write_all(&[0; 4])?;
    out.write_all(&(image_bytes as u32).to_le_bytes())?;
    out.write_all(&[0; 16])?;
    for y in (0..layout.height as usize).rev() {
        let row = &rgba[y * layout.stride as usize..y * layout.stride as usize + row_bytes];
        for pixel in row.chunks_exact(4) {
            out.write_all(&[pixel[2], pixel[1], pixel[0], pixel[3]])?;
        }
    }
    out.flush()?;
    Ok(())
}
