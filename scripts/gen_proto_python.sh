#!/usr/bin/env bash
# SPDX-License-Identifier: AGPL-3.0-only
#
# Regenerate the controller's Python protobuf bindings from the shared schema.
#
# Usage (from anywhere):
#   scripts/gen_proto_python.sh
#
# Requirements:
#   - protoc (the same major/minor as the installed `protobuf` Python runtime;
#     the generated modules embed a runtime-version check)
#   - bash
#
# Output:
#   controller/proto_gen/ozma/v1/*_pb2.py
#
# The generated modules import each other as `from ozma.v1 import ...`.
# `controller/display_protocol.py` puts `controller/proto_gen` first on
# sys.path so those imports resolve to these checked-in bindings.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PROTO_DIR="$ROOT/proto"
OUT_DIR="$ROOT/controller/proto_gen"

if ! command -v protoc >/dev/null 2>&1; then
  echo "error: protoc is not installed" >&2
  echo "       install the protobuf compiler or run this script in the build image" >&2
  exit 1
fi

PROTOC_VERSION="$(protoc --version | awk '{print $2}')"
echo "Using protoc $PROTOC_VERSION"

if [[ ! -d "$PROTO_DIR/ozma/v1" ]]; then
  echo "error: missing proto sources at $PROTO_DIR/ozma/v1" >&2
  exit 1
fi

mkdir -p "$OUT_DIR/ozma/v1"

# Remove stale generated modules so deleted .proto files do not linger.
rm -f "$OUT_DIR"/ozma/v1/*_pb2.py
find "$OUT_DIR" -type d -name __pycache__ -prune -exec rm -rf {} +

protoc \
  --python_out="$OUT_DIR" \
  -I "$PROTO_DIR" \
  "$PROTO_DIR"/ozma/v1/*.proto

# protoc does not emit package markers for Python.  The top-level package
# marker also puts this directory on sys.path so generated modules can import
# each other as ``ozma.v1.*`` even when imported as ``proto_gen.ozma.v1``.
cat > "$OUT_DIR/__init__.py" <<'PYEOF'
# SPDX-License-Identifier: AGPL-3.0-only
"""Generated Python protobuf bindings for proto/ozma/v1.

The modules import each other as ``ozma.v1.*``.  Add this directory to
``sys.path`` before importing them (``controller/display_protocol.py`` does
this automatically), including for direct ``proto_gen.ozma.v1`` imports.
"""

import sys as _sys
from pathlib import Path as _Path

_GEN_DIR = str(_Path(__file__).resolve().parent)
if _GEN_DIR not in _sys.path:
    _sys.path.insert(0, _GEN_DIR)

del _sys, _Path
PYEOF

touch "$OUT_DIR/ozma/__init__.py" "$OUT_DIR/ozma/v1/__init__.py"

# Keep the generated tree reproducible and easy to identify.
cat > "$OUT_DIR/README.md" <<EOF
# Generated protobuf bindings

Do not edit these files by hand.

Regenerate from the repository root with:

\`\`\`sh
scripts/gen_proto_python.sh
\`\`\`

Generated by protoc $PROTOC_VERSION from \`proto/ozma/v1/*.proto\`.
The modules import each other as \`ozma.v1.*\`; \`controller/display_protocol.py\`
adds this directory to \`sys.path\`.
EOF

echo "Generated Python protobuf bindings in $OUT_DIR"
