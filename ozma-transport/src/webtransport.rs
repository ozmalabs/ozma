/// Path a WebTransport session request must target.
pub const SESSION_PATH: &str = "/session";

/// Maximum reliable-stream frame accepted from a peer. Matches the native QUIC
/// adapter so a corrupt length prefix cannot force an unbounded allocation.
const MAX_FRAME_LEN: usize = 8 * 1024 * 1024;

/// Largest read handed to the incremental decoder at once.
const READ_CHUNK: usize = 64 * 1024;

/// Configuration for the WebTransport listener and the proof client.
#[derive(Clone, Debug)]
pub struct WebTransportConfig {
    /// DNS/IP names placed in the generated self-signed certificate. The bind
    /// host is added automatically.
    pub certificate_names: Vec<String>,
    /// Timeout for the H3 handshake, the session request, and the control
    /// bi-directional stream.
    pub handshake_timeout: Duration,
    /// Idle timeout for the QUIC connection.
    pub idle_timeout: Duration,
    /// Optional keep-alive interval.
    pub keep_alive_interval: Option<Duration>,
    /// Bounded receive queue between the reader task and `recv`.
    pub event_queue: usize,
}

impl Default for WebTransportConfig {
    fn default() -> Self {
        Self {
            certificate_names: vec![
                "localhost".to_string(),
                "127.0.0.1".to_string(),
                "::1".to_string(),
            ],
            handshake_timeout: Duration::from_secs(5),
            idle_timeout: Duration::from_secs(30),
            keep_alive_interval: None,
            event_queue: 64,
        }
    }
}

impl WebTransportConfig {
    /// Set the H3 handshake timeout.
    pub fn with_handshake_timeout(mut self, duration: Duration) -> Self {
        self.handshake_timeout = duration;
        self
    }

    /// Set the QUIC idle timeout.
    pub fn with_idle_timeout(mut self, duration: Duration) -> Self {
        self.idle_timeout = duration;
        self
    }
}

/// A bound WebTransport listener with the certificate material clients pin.
pub struct WebTransportServer {
    endpoint: Endpoint<ServerSide>,
    local_addr: SocketAddr,
    certificate_der: Vec<u8>,
    certificate_sha256: [u8; 32],
    fingerprint: String,
    config: WebTransportConfig,
    channels: ChannelMap,
}

impl fmt::Debug for WebTransportServer {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("WebTransportServer")
            .field("local_addr", &self.local_addr)
            .field("fingerprint", &self.fingerprint)
            .field("channels", &self.channels.len())
            .finish()
    }
}

impl WebTransportServer {
    /// Bind on `addr` with the default configuration and session channels.
    ///
    /// Port `0` requests an ephemeral port; read it back with [`Self::local_addr`].
    /// Must be called from within a Tokio runtime.
    pub fn bind(addr: SocketAddr) -> Result<Self> {
        Self::bind_with_config(
            addr,
            WebTransportConfig::default(),
            ChannelMap::default_session(),
        )
    }

    /// Bind with an explicit configuration and channel map.
    pub fn bind_with_config(
        addr: SocketAddr,
        config: WebTransportConfig,
        channels: ChannelMap,
    ) -> Result<Self> {
        let identity =
            Identity::self_signed(certificate_names(&config, addr.ip())).map_err(|error| {
                ApiError::internal(format!(
                    "failed to generate the WebTransport test identity: {error}"
                ))
            })?;
        let certificate = identity
            .certificate_chain()
            .as_slice()
            .first()
            .cloned()
            .ok_or_else(|| ApiError::internal("WebTransport identity has no certificate"))?;
        let certificate_der = certificate.der().to_vec();
        let certificate_sha256 = *certificate.hash().as_ref();
        let fingerprint = hex_digest(&certificate_sha256);

        let mut builder = ServerConfig::builder()
            .with_bind_address(addr)
            .with_identity(identity)
            .keep_alive_interval(config.keep_alive_interval);
        builder = builder
            .max_idle_timeout(Some(config.idle_timeout))
            .map_err(|_| ApiError::invalid("WebTransport idle timeout is too large"))?;
        let endpoint = Endpoint::server(builder.build()).map_err(|error| {
            ApiError::internal(format!(
                "failed to bind WebTransport endpoint on {addr}: {error}"
            ))
        })?;
        let local_addr = endpoint
            .local_addr()
            .map_err(|error| ApiError::internal(format!("WebTransport local address: {error}")))?;

        Ok(Self {
            endpoint,
            local_addr,
            certificate_der,
            certificate_sha256,
            fingerprint,
            config,
            channels,
        })
    }

    /// The bound address, including the real port when `0` was requested.
    pub fn local_addr(&self) -> SocketAddr {
        self.local_addr
    }

    /// The advertised `https://host:port/session` URL.
    pub fn session_url(&self) -> String {
        self.url(SESSION_PATH)
    }

    /// Build an `https://host:port<path>` URL for this listener.
    pub fn url(&self, path: &str) -> String {
        let host = match self.local_addr.ip() {
            IpAddr::V4(ip) if ip.is_unspecified() => "localhost".to_string(),
            IpAddr::V6(ip) if ip.is_unspecified() => "localhost".to_string(),
            IpAddr::V4(ip) => ip.to_string(),
            IpAddr::V6(ip) => format!("[{ip}]"),
        };
        let path = if path.starts_with('/') {
            path.to_string()
        } else {
            format!("/{path}")
        };
        format!("https://{host}:{}{path}", self.local_addr.port())
    }

    /// DER certificate the browser pins through `serverCertificateHashes`.
    pub fn certificate_der(&self) -> &[u8] {
        &self.certificate_der
    }

    /// Raw SHA-256 of [`Self::certificate_der`].
    pub fn certificate_sha256(&self) -> [u8; 32] {
        self.certificate_sha256
    }

    /// Lowercase hex SHA-256 fingerprint of the DER certificate.
    pub fn fingerprint(&self) -> &str {
        &self.fingerprint
    }

    /// The server's channel map (for diagnostics).
    pub fn channel_map(&self) -> &ChannelMap {
        &self.channels
    }

    /// Wait for one session request, accept its single bidirectional control
    /// stream, and return a live transport.
    pub async fn accept(&self) -> Result<WebTransportSession> {
        let incoming = timeout(self.config.handshake_timeout, self.endpoint.accept())
            .await
            .map_err(|_| {
                timeout_error(
                    "waiting for a WebTransport session request",
                    self.config.handshake_timeout,
                )
            })?;
        let request = timeout(self.config.handshake_timeout, incoming)
            .await
            .map_err(|_| {
                timeout_error(
                    "reading the WebTransport session request",
                    self.config.handshake_timeout,
                )
            })?
            .map_err(|error| connection_error("session request", error))?;

        if request.path() != SESSION_PATH {
            let path = request.path().to_string();
            request.not_found().await;
            return Err(transport_unavailable(format!(
                "WebTransport session request for unsupported path {path}"
            )));
        }

        let connection = timeout(self.config.handshake_timeout, request.accept())
            .await
            .map_err(|_| {
                timeout_error(
                    "accepting the WebTransport session",
                    self.config.handshake_timeout,
                )
            })?
            .map_err(|error| connection_error("session accept", error))?;

        let (send, recv) = timeout(self.config.handshake_timeout, connection.accept_bi())
            .await
            .map_err(|_| {
                timeout_error(
                    "accepting the WebTransport control stream",
                    self.config.handshake_timeout,
                )
            })?
            .map_err(|error| connection_error("control stream", error))?;

        tracing::debug!(
            remote = %connection.remote_address(),
            "accepted WebTransport session"
        );
        Ok(WebTransportSession::start(
            connection,
            send,
            recv,
            self.channels.clone(),
            &self.config,
            None,
        ))
    }

    /// Stop accepting new sessions.
    pub fn close(&self) {
        self.endpoint.close(VarInt::from_u32(0), b"server closed");
    }
}

/// A native WebTransport proof client.
#[derive(Clone, Copy, Debug, Default)]
pub struct WebTransportClient;

impl WebTransportClient {
    /// Connect to `url` (`https://host:port/session`), pinning the SHA-256 of
    /// the DER certificate the listener presents.
    pub async fn connect(
        url: &str,
        certificate_sha256: [u8; 32],
        channels: ChannelMap,
    ) -> Result<WebTransportSession> {
        Self::connect_with_config(
            url,
            certificate_sha256,
            WebTransportConfig::default(),
            channels,
        )
        .await
    }

    /// Connect with an explicit configuration.
    pub async fn connect_with_config(
        url: &str,
        certificate_sha256: [u8; 32],
        config: WebTransportConfig,
        channels: ChannelMap,
    ) -> Result<WebTransportSession> {
        let mut builder = ClientConfig::builder()
            .with_bind_default()
            .with_server_certificate_hashes([Sha256Digest::new(certificate_sha256)]);
        builder = builder
            .max_idle_timeout(Some(config.idle_timeout))
            .map_err(|_| ApiError::invalid("WebTransport idle timeout is too large"))?
            .keep_alive_interval(config.keep_alive_interval);
        let endpoint = Endpoint::client(builder.build()).map_err(|error| {
            ApiError::internal(format!(
                "failed to create WebTransport client endpoint: {error}"
            ))
        })?;
        Self::connect_with_endpoint(url, &config, channels, endpoint).await
    }

    /// Connect without validating the server certificate.
    ///
    /// Only available with the `webtransport-insecure` feature. It exists for
    /// local bring-up and unit tests; production clients pin a hash instead.
    #[cfg(feature = "webtransport-insecure")]
    pub async fn connect_without_validation(
        url: &str,
        channels: ChannelMap,
    ) -> Result<WebTransportSession> {
        Self::connect_without_validation_with_config(url, WebTransportConfig::default(), channels)
            .await
    }

    /// [`Self::connect_without_validation`] with an explicit configuration.
    #[cfg(feature = "webtransport-insecure")]
    pub async fn connect_without_validation_with_config(
        url: &str,
        config: WebTransportConfig,
        channels: ChannelMap,
    ) -> Result<WebTransportSession> {
        let mut builder = ClientConfig::builder()
            .with_bind_default()
            .with_no_cert_validation();
        builder = builder
            .max_idle_timeout(Some(config.idle_timeout))
            .map_err(|_| ApiError::invalid("WebTransport idle timeout is too large"))?
            .keep_alive_interval(config.keep_alive_interval);
        let endpoint = Endpoint::client(builder.build()).map_err(|error| {
            ApiError::internal(format!(
                "failed to create WebTransport client endpoint: {error}"
            ))
        })?;
        Self::connect_with_endpoint(url, &config, channels, endpoint).await
    }

    async fn connect_with_endpoint(
        url: &str,
        config: &WebTransportConfig,
        channels: ChannelMap,
        endpoint: Endpoint<ClientSide>,
    ) -> Result<WebTransportSession> {
        let connection = timeout(config.handshake_timeout, endpoint.connect(url))
            .await
            .map_err(|_| timeout_error("connecting over WebTransport", config.handshake_timeout))?
            .map_err(|error| connection_error("connect", error))?;

        let (send, recv) = timeout(config.handshake_timeout, connection.open_bi())
            .await
            .map_err(|_| {
                timeout_error(
                    "opening the WebTransport control stream",
                    config.handshake_timeout,
                )
            })?
            .map_err(|error| connection_error("control stream open", error))?
            .await
            .map_err(|error| connection_error("control stream open", error))?;

        tracing::debug!(%url, "connected WebTransport session");
        Ok(WebTransportSession::start(
            connection,
            send,
            recv,
            channels,
            config,
            Some(endpoint),
        ))
    }
}

struct Inner {
    connection: Connection,
    send: Mutex<SendStream>,
    closed: AtomicBool,
    metrics: Arc<Metrics>,
}

/// A live WebTransport session transport.
///
/// Returned by [`WebTransportServer::accept`] or [`WebTransportClient::connect`].
pub struct WebTransportSession {
    inner: Arc<Inner>,
    rx: mpsc::Receiver<TransportEvent>,
    map: ChannelMap,
    client_endpoint: Option<Endpoint<ClientSide>>,
    recv_closed: Option<CloseReason>,
    reader: JoinHandle<()>,
}

impl fmt::Debug for WebTransportSession {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("WebTransportSession")
            .field("remote_address", &self.inner.connection.remote_address())
            .field("channels", &self.map.len())
            .field("closed", &self.is_closed())
            .finish()
    }
}

impl WebTransportSession {
    fn start(
        connection: Connection,
        send: SendStream,
        recv: RecvStream,
        map: ChannelMap,
        config: &WebTransportConfig,
        client_endpoint: Option<Endpoint<ClientSide>>,
    ) -> Self {
        let metrics = Arc::new(Metrics::default());
        let closed_once = Arc::new(AtomicBool::new(false));
        let (tx, rx) = mpsc::channel(config.event_queue.max(1));

        let reader = tokio::spawn(read_session(
            recv,
            connection.clone(),
            tx,
            map.clone(),
            metrics.clone(),
            closed_once,
        ));

        Self {
            inner: Arc::new(Inner {
                connection,
                send: Mutex::new(send),
                closed: AtomicBool::new(false),
                metrics,
            }),
            rx,
            map,
            client_endpoint,
            recv_closed: None,
            reader,
        }
    }

    /// The connected peer address.
    pub fn remote_address(&self) -> SocketAddr {
        self.inner.connection.remote_address()
    }

    /// Send one bounded resource over a dedicated unidirectional stream, so a
    /// slow resource does not block the reliable control stream.
    pub async fn send_resource(&self, payload: Bytes) -> Result<()> {
        if self.inner.closed.load(Ordering::SeqCst) {
            self.inner.metrics.record_send_error();
            return Err(channel_closed(None, CloseReason::LocalShutdown));
        }
        self.map.check_payload(ChannelId::BULK, payload.len())?;
        let mut stream = self
            .inner
            .connection
            .open_uni()
            .await
            .map_err(resource_error)?
            .await
            .map_err(resource_error)?;
        stream.write_all(&payload).await.map_err(resource_error)?;
        stream.finish().await.map_err(resource_error)?;
        self.inner.metrics.record_sent(payload.len(), false);
        Ok(())
    }

    /// Receive one bounded resource from a unidirectional stream.
    ///
    /// Resource receive is optional for a session peer; this exists so the
    /// native proof client and tests can verify byte equality.
    pub async fn recv_resource(&self) -> Result<Bytes> {
        let limit = self.map.require(ChannelId::BULK)?.max_payload as usize;
        let mut stream = self
            .inner
            .connection
            .accept_uni()
            .await
            .map_err(resource_error)?;
        let mut payload = Vec::new();
        let mut chunk = vec![0u8; READ_CHUNK];
        loop {
            match stream.read(&mut chunk).await.map_err(resource_error)? {
                Some(0) => continue,
                Some(read) => {
                    if payload.len().saturating_add(read) > limit {
                        return Err(payload_too_large(
                            ChannelId::BULK,
                            payload.len().saturating_add(read),
                            limit,
                        ));
                    }
                    payload.extend_from_slice(&chunk[..read]);
                }
                None => break,
            }
        }
        self.inner.metrics.record_received(payload.len(), false);
        Ok(Bytes::from(payload))
    }
}

#[async_trait]
impl SessionTransport for WebTransportSession {
    fn mode(&self) -> TransportMode {
        TransportMode::Quic
    }

    fn channel_map(&self) -> &ChannelMap {
        &self.map
    }

    async fn send(&self, channel: ChannelId, payload: Bytes) -> Result<()> {
        if self.inner.closed.load(Ordering::SeqCst) {
            self.inner.metrics.record_send_error();
            return Err(channel_closed(Some(channel), CloseReason::LocalShutdown));
        }
        self.map.check_payload(channel, payload.len())?;

        if self.map.is_reliable(channel)? {
            let frame = encode_reliable(channel, &payload);
            let mut send = self.inner.send.lock().await;
            if let Err(error) = send.write_all(&frame).await {
                self.inner.metrics.record_send_error();
                self.inner.metrics.mark_closed();
                return Err(transport_unavailable(format!(
                    "WebTransport stream send failed: {error}"
                )));
            }
            self.inner.metrics.record_sent(payload.len(), false);
            return Ok(());
        }

        let Some(max) = self.inner.connection.max_datagram_size() else {
            self.inner.metrics.record_send_error();
            return Err(ApiError::new(
                ozma_protocol::codes::UNSUPPORTED,
                "peer does not support WebTransport datagrams",
            )
            .with_remediation(
                "Use a reliable channel or a WebTransport endpoint with datagrams.",
            ));
        };
        let datagram = encode_datagram(channel, &payload, Some(max))?;
        match self.inner.connection.send_datagram(&datagram) {
            Ok(()) => {
                self.inner.metrics.record_sent(payload.len(), true);
                Ok(())
            }
            Err(wtransport::error::SendDatagramError::TooLarge) => {
                self.inner.metrics.record_send_error();
                Err(payload_too_large(
                    channel,
                    payload.len(),
                    max.saturating_sub(1),
                ))
            }
            Err(wtransport::error::SendDatagramError::UnsupportedByPeer) => {
                self.inner.metrics.record_send_error();
                Err(ApiError::new(
                    ozma_protocol::codes::UNSUPPORTED,
                    "WebTransport datagrams are not available on this connection",
                ))
            }
            Err(wtransport::error::SendDatagramError::NotConnected) => {
                self.inner.metrics.record_send_error();
                self.inner.metrics.mark_closed();
                Err(transport_unavailable(
                    "WebTransport datagram send failed: connection closed",
                ))
            }
        }
    }

    async fn recv(&mut self) -> TransportEvent {
        if let Some(reason) = self.recv_closed {
            return TransportEvent::Closed { reason };
        }
        match self.rx.recv().await {
            Some(event) => {
                if let TransportEvent::Closed { reason } = event {
                    self.recv_closed = Some(reason);
                    self.inner.metrics.mark_closed();
                }
                event
            }
            None => {
                let reason = CloseReason::TransportError;
                self.recv_closed = Some(reason);
                self.inner.metrics.mark_closed();
                TransportEvent::Closed { reason }
            }
        }
    }

    async fn send_resource(&self, payload: Bytes) -> Result<()> {
        WebTransportSession::send_resource(self, payload).await
    }

    async fn close_with_reason(&self, reason: CloseReason) -> Result<()> {
        if self.inner.closed.swap(true, Ordering::SeqCst) {
            return Ok(());
        }
        self.inner.metrics.mark_closed();
        self.inner
            .connection
            .close(VarInt::from_u32(0), reason.as_str().as_bytes());
        if let Some(endpoint) = &self.client_endpoint {
            endpoint.close(VarInt::from_u32(0), b"session closed");
        }
        Ok(())
    }

    fn metrics(&self) -> TransportMetrics {
        let mut snapshot = self.inner.metrics.snapshot(TransportMode::Quic);
        snapshot.closed |= self.recv_closed.is_some();
        snapshot
    }
}

impl Drop for WebTransportSession {
    fn drop(&mut self) {
        self.reader.abort();
        if !self.inner.closed.swap(true, Ordering::SeqCst) {
            self.inner.metrics.mark_closed();
            self.inner
                .connection
                .close(VarInt::from_u32(0), b"transport dropped");
        }
    }
}

async fn read_session(
    mut recv: RecvStream,
    connection: Connection,
    tx: mpsc::Sender<TransportEvent>,
    map: ChannelMap,
    metrics: Arc<Metrics>,
    closed_once: Arc<AtomicBool>,
) {
    let mut decoder = FrameDecoder::new(MAX_FRAME_LEN);
    let mut chunk = vec![0u8; READ_CHUNK];
    loop {
        tokio::select! {
            read = recv.read(&mut chunk) => {
                match read {
                    Ok(Some(len)) => {
                        let frames = match decoder.push(&chunk[..len]) {
                            Ok(frames) => frames,
                            Err(error) => {
                                emit_error(&tx, &metrics, error).await;
                                finish_closed(&tx, &closed_once, &metrics, CloseReason::ProtocolError)
                                    .await;
                                return;
                            }
                        };
                        for (channel, payload) in frames {
                            if !accept_reliable(&tx, &metrics, &map, channel, &payload).await {
                                return;
                            }
                        }
                    }
                    Ok(None) => {
                        finish_closed(&tx, &closed_once, &metrics, CloseReason::PeerClosed).await;
                        return;
                    }
                    Err(error) => {
                        finish_closed(&tx, &closed_once, &metrics, reason_for_stream_error(error))
                            .await;
                        return;
                    }
                }
            }
            datagram = connection.receive_datagram() => {
                match datagram {
                    Ok(datagram) => {
                        let payload = datagram.payload();
                        if !accept_datagram(&tx, &metrics, &map, &payload).await {
                            return;
                        }
                    }
                    Err(error) => {
                        finish_closed(&tx, &closed_once, &metrics, reason_for_connection_error(error))
                            .await;
                        return;
                    }
                }
            }
        }
    }
}

/// Validate one reliable frame and queue it. Returns `false` when the receiver
/// went away and the reader should stop.
async fn accept_reliable(
    tx: &mpsc::Sender<TransportEvent>,
    metrics: &Metrics,
    map: &ChannelMap,
    channel: ChannelId,
    payload: &[u8],
) -> bool {
    let Some(descriptor) = map.get(channel) else {
        emit_error(tx, metrics, channel_unknown(channel)).await;
        return true;
    };
    if !descriptor.reliable {
        emit_error(
            tx,
            metrics,
            protocol_error(format!(
                "channel {channel} is unreliable but arrived on the control stream"
            )),
        )
        .await;
        return true;
    }
    if payload.len() > descriptor.max_payload as usize {
        emit_error(
            tx,
            metrics,
            payload_too_large(channel, payload.len(), descriptor.max_payload as usize),
        )
        .await;
        return true;
    }
    metrics.record_received(payload.len(), false);
    tx.send(TransportEvent::Payload {
        channel,
        payload: Bytes::copy_from_slice(payload),
    })
    .await
    .is_ok()
}

/// Validate one datagram and queue it. Returns `false` when the receiver is
/// gone.
async fn accept_datagram(
    tx: &mpsc::Sender<TransportEvent>,
    metrics: &Metrics,
    map: &ChannelMap,
    datagram: &[u8],
) -> bool {
    let Some((&raw, payload)) = datagram.split_first() else {
        emit_error(tx, metrics, protocol_error("empty WebTransport datagram")).await;
        return true;
    };
    let channel = ChannelId::new(raw);
    let Some(descriptor) = map.get(channel) else {
        emit_error(tx, metrics, channel_unknown(channel)).await;
        return true;
    };
    if descriptor.reliable {
        emit_error(
            tx,
            metrics,
            protocol_error(format!(
                "channel {channel} is reliable but arrived as a datagram"
            )),
        )
        .await;
        return true;
    }
    if payload.len() > descriptor.max_payload as usize {
        emit_error(
            tx,
            metrics,
            payload_too_large(channel, payload.len(), descriptor.max_payload as usize),
        )
        .await;
        return true;
    }
    metrics.record_received(payload.len(), true);
    tx.send(TransportEvent::Datagram {
        channel,
        payload: Bytes::copy_from_slice(payload),
    })
    .await
    .is_ok()
}

async fn emit_error(tx: &mpsc::Sender<TransportEvent>, metrics: &Metrics, error: ApiError) {
    metrics.record_receive_error();
    let _ = tx.send(TransportEvent::Error { error }).await;
}

async fn finish_closed(
    tx: &mpsc::Sender<TransportEvent>,
    closed_once: &AtomicBool,
    metrics: &Metrics,
    reason: CloseReason,
) {
    metrics.mark_closed();
    if !closed_once.swap(true, Ordering::SeqCst) {
        let _ = tx.send(TransportEvent::Closed { reason }).await;
    }
}

fn reason_for_stream_error(error: wtransport::error::StreamReadError) -> CloseReason {
    use wtransport::error::StreamReadError;
    match error {
        StreamReadError::NotConnected => CloseReason::TransportError,
        StreamReadError::Reset(_) => CloseReason::ProtocolError,
        StreamReadError::QuicProto => CloseReason::TransportError,
    }
}

fn reason_for_connection_error(error: wtransport::error::ConnectionError) -> CloseReason {
    use wtransport::error::ConnectionError;
    match error {
        ConnectionError::ApplicationClosed(_) => CloseReason::PeerClosed,
        ConnectionError::LocallyClosed => CloseReason::LocalShutdown,
        ConnectionError::TimedOut => CloseReason::Timeout,
        _ => CloseReason::TransportError,
    }
}

fn connection_error(context: &str, error: impl fmt::Display) -> ApiError {
    transport_unavailable(format!("WebTransport {context} failed: {error}"))
}

fn resource_error(error: impl fmt::Display) -> ApiError {
    transport_unavailable(format!("WebTransport resource stream failed: {error}"))
}

fn timeout_error(what: &str, duration: Duration) -> ApiError {
    transport_unavailable(format!(
        "timed out {what} after {} ms",
        duration.as_millis()
    ))
}

/// The certificate names for a listener: the configured names plus the bind
/// host, de-duplicated so `Identity::self_signed` does not emit duplicate SANs.
fn certificate_names(config: &WebTransportConfig, bind: IpAddr) -> Vec<String> {
    let mut names = Vec::with_capacity(config.certificate_names.len() + 1);
    for name in config
        .certificate_names
        .iter()
        .chain(std::iter::once(&bind.to_string()))
    {
        if !name.trim().is_empty() && !names.iter().any(|existing| existing == name) {
            names.push(name.clone());
        }
    }
    names
}

fn hex_digest(digest: &[u8; 32]) -> String {
    let mut hex = String::with_capacity(64);
    for byte in digest {
        use std::fmt::Write as _;
        let _ = write!(hex, "{byte:02x}");
    }
    hex
}

/// Encode one reliable frame: `[channel u8][length u32 BE][payload]`.
///
/// Byte-identical to `ozma_client_core::framing::encode_reliable`.
fn encode_reliable(channel: ChannelId, payload: &[u8]) -> Vec<u8> {
    let mut frame = Vec::with_capacity(5 + payload.len());
    frame.push(channel.raw());
    frame.extend_from_slice(&(payload.len() as u32).to_be_bytes());
    frame.extend_from_slice(payload);
    frame
}

/// Encode one datagram: `[channel u8][payload]`.
///
/// Byte-identical to `ozma_client_core::framing::encode_datagram`.
fn encode_datagram(channel: ChannelId, payload: &[u8], capacity: Option<usize>) -> Result<Vec<u8>> {
    if let Some(capacity) = capacity {
        if payload.len().saturating_add(1) > capacity {
            return Err(payload_too_large(
                channel,
                payload.len(),
                capacity.saturating_sub(1),
            ));
        }
    }
    let mut datagram = Vec::with_capacity(1 + payload.len());
    datagram.push(channel.raw());
    datagram.extend_from_slice(payload);
    Ok(datagram)
}

/// Incremental decoder for the reliable stream, matching
/// `ozma_client_core::framing::FrameDecoder`.
struct FrameDecoder {
    buffer: Vec<u8>,
    max_payload: usize,
}

impl FrameDecoder {
    fn new(max_payload: usize) -> Self {
        Self {
            buffer: Vec::new(),
            max_payload,
        }
    }

    fn push(&mut self, bytes: &[u8]) -> Result<Vec<(ChannelId, Bytes)>> {
        const HEADER: usize = 5;
        self.buffer.extend_from_slice(bytes);
        let mut frames = Vec::new();
        let mut offset = 0;
        while self.buffer.len() - offset >= HEADER {
            let channel = ChannelId::new(self.buffer[offset]);
            let length = u32::from_be_bytes([
                self.buffer[offset + 1],
                self.buffer[offset + 2],
                self.buffer[offset + 3],
                self.buffer[offset + 4],
            ]) as usize;
            if length > self.max_payload {
                return Err(payload_too_large(channel, length, self.max_payload));
            }
            if self.buffer.len() - offset - HEADER < length {
                break;
            }
            let start = offset + HEADER;
            let end = start + length;
            frames.push((channel, Bytes::copy_from_slice(&self.buffer[start..end])));
            offset = end;
        }
        if offset > 0 {
            self.buffer.drain(..offset);
        }
        Ok(frames)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::net::Ipv4Addr;

    #[tokio::test]
    async fn certificate_hash_and_url_helpers_are_consistent() {
        let server = WebTransportServer::bind(SocketAddr::from((Ipv4Addr::LOCALHOST, 0))).unwrap();
        let addr = server.local_addr();
        assert_ne!(addr.port(), 0);
        assert!(!server.certificate_der().is_empty());
        assert_eq!(server.certificate_sha256(), server.certificate_sha256());
        assert_eq!(
            server.fingerprint(),
            hex_digest(&server.certificate_sha256())
        );
        assert_eq!(server.fingerprint().len(), 64);
        assert!(server
            .fingerprint()
            .chars()
            .all(|character| character.is_ascii_hexdigit() && !character.is_ascii_uppercase()));
        assert_eq!(
            server.session_url(),
            format!("https://127.0.0.1:{}/session", addr.port())
        );
        assert_eq!(
            server.url("probe"),
            format!("https://127.0.0.1:{}/probe", addr.port())
        );
        assert_eq!(
            server.url("/nested/path"),
            format!("https://127.0.0.1:{}/nested/path", addr.port())
        );
    }

    #[test]
    fn framing_is_byte_identical_to_client_core() {
        // `[channel][len u32 BE][payload]` and `[channel][payload]`; the
        // constants are duplicated so a drift in either crate fails here.
        let frame = encode_reliable(ChannelId::CONTROL, b"hello");
        assert_eq!(&frame[..5], &[0, 0, 0, 0, 5]);
        assert_eq!(&frame[5..], b"hello");

        let datagram = encode_datagram(ChannelId::VIDEO, b"fragment", Some(1200)).unwrap();
        assert_eq!(datagram[0], ChannelId::VIDEO.raw());
        assert_eq!(&datagram[1..], b"fragment");
        assert!(encode_datagram(ChannelId::VIDEO, &[0u8; 1200], Some(1200)).is_err());
    }

    #[test]
    fn decoder_reassembles_frames_split_across_chunks() {
        let mut stream = encode_reliable(ChannelId::CONTROL, b"hello");
        stream.extend_from_slice(&encode_reliable(ChannelId::AUDIO, b"world"));
        let mut decoder = FrameDecoder::new(MAX_FRAME_LEN);
        assert!(decoder.push(&stream[..3]).unwrap().is_empty());
        let frames = decoder.push(&stream[3..]).unwrap();
        assert_eq!(frames.len(), 2);
        assert_eq!(frames[0].0, ChannelId::CONTROL);
        assert_eq!(frames[0].1.as_ref(), b"hello");
        assert_eq!(frames[1].0, ChannelId::AUDIO);
        assert_eq!(frames[1].1.as_ref(), b"world");
    }
}
