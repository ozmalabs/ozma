//! Native WebTransport (HTTP/3) adapter.
//!
//! This is the listener a browser connects to and the proof client used by
//! native tests. It carries exactly the same session as [`crate::quic`]:
//!
//! - one reliable, ordered bidirectional WebTransport stream for `control`,
//!   `input`, `telemetry`, and `bulk` channels;
//! - WebTransport datagrams for `video`, `audio`, and `mic` channels;
//! - dedicated unidirectional streams for bounded resources.
//!
//! Stream frames are `[channel: u8][length: u32 BE][payload]`; datagrams are
//! `[channel: u8][payload]`. These bytes are identical to
//! `ozma_client_core::framing`, which the native and wasm clients share. The
//! encoding lives here as well because `ozma-client-core` already depends on
//! this crate, so depending on it back would form a cycle.
//!
//! The identity is generated by `wtransport`: an ECDSA P-256 certificate with
//! a 14-day validity, which is what the W3C `serverCertificateHashes` pinning
//! path requires. It is therefore a *different* certificate from the raw QUIC
//! listener; clients must pin the SHA-256 exposed here.

